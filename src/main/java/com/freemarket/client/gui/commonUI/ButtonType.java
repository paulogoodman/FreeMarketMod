package com.freemarket.client.gui.commonUI;

/**
 * Enum representing the type of button that was clicked on a card.
 */
public enum ButtonType {
    /** Buy button was clicked */
    BUY,
    
    /** Sell button was clicked */
    SELL,
    
    /** Bid button was clicked */
    BID,
    
    /** Cancel auction button was clicked */
    CANCEL_AUCTION,
    
    /** Delete/manage button was clicked */
    MANAGE,
    
    /** No button was clicked */
    NONE
}

